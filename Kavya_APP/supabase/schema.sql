-- Unlocks for the two fixed default media panels, tracked per user so they can
-- be re-opened without paying again.
create table if not exists public.featured_media_unlocks (
  user_id uuid not null references public.profiles(id) on delete cascade,
  slot integer not null check (slot in (1, 2)),
  unlocked_at timestamptz not null default now(),
  primary key (user_id, slot)
);

alter table public.featured_media_unlocks enable row level security;

drop policy if exists "Users can read their own featured unlocks" on public.featured_media_unlocks;
create policy "Users can read their own featured unlocks"
  on public.featured_media_unlocks for select to authenticated
  using (user_id = auth.uid());

create or replace function public.unlock_featured_media_for_current_user(p_slot integer)
returns json
language plpgsql
security definer set search_path = public
as $$
declare
  featured_item public.featured_media;
  current_user_id uuid := auth.uid();
  current_user_credits integer;
  new_credit_balance integer;
begin
  select * into featured_item from public.featured_media where slot = p_slot;
  if not found then
    return json_build_object('status', 'error', 'message', 'FEATURED_MEDIA_NOT_FOUND');
  end if;

  if exists (select 1 from public.featured_media_unlocks where user_id = current_user_id and slot = p_slot) then
    return json_build_object('status', 'already_unlocked', 'slot', p_slot, 'credits_balance', (select credits from public.profiles where id = current_user_id));
  end if;

  select credits into current_user_credits from public.profiles where id = current_user_id;
  if current_user_credits < featured_item.credit_cost then
    return json_build_object('status', 'INSUFFICIENT_CREDITS', 'slot', p_slot);
  end if;

  update public.profiles
  set credits = credits - featured_item.credit_cost
  where id = current_user_id
  returning credits into new_credit_balance;

  insert into public.featured_media_unlocks (user_id, slot)
  values (current_user_id, p_slot);
  insert into public.credit_transactions (
    user_id, transaction_type, amount, balance_after, reference_id, description
  )
  values (
    current_user_id, 'media_unlock', -featured_item.credit_cost, new_credit_balance,
    concat('featured-', p_slot), concat('Unlocked default media ', featured_item.title)
  );

  return json_build_object('status', 'unlocked', 'slot', p_slot, 'credits_balance', new_credit_balance);
end;
$$;

revoke all on function public.unlock_featured_media_for_current_user(integer) from public;
grant execute on function public.unlock_featured_media_for_current_user(integer) to authenticated;
