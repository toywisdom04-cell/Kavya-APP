-- Called from the verified Cashfree webhook. The status predicate makes credit
-- fulfilment idempotent when Cashfree retries a webhook.
create or replace function public.fulfill_cashfree_order(
  p_cashfree_order_id text,
  p_cashfree_payment_id text
)
returns boolean
language plpgsql
security definer set search_path = public
as $$
declare
  paid_order public.payment_orders;
  buyer_profile public.profiles;
begin
  update public.payment_orders
  set status = 'paid', cashfree_payment_id = p_cashfree_payment_id, paid_at = now()
  where cashfree_order_id = p_cashfree_order_id and status = 'created'
  returning * into paid_order;

  if not found then return false; end if;

  update public.profiles
  set credits = credits + paid_order.credits_to_add,
      tier_status = paid_order.tier_status
  where id = paid_order.user_id
  returning * into buyer_profile;

  insert into public.buyer_records (
    user_id, email, mobile, plan_id, amount_paise, credits_purchased,
    cashfree_order_id, cashfree_payment_id, paid_at
  )
  values (
    paid_order.user_id, buyer_profile.email, paid_order.mobile, paid_order.plan_id,
    paid_order.amount_paise, paid_order.credits_to_add, paid_order.cashfree_order_id,
    paid_order.cashfree_payment_id, paid_order.paid_at
  );

  insert into public.credit_transactions (
    user_id, transaction_type, amount, balance_after, reference_id, description
  )
  values (
    paid_order.user_id, 'purchase', paid_order.credits_to_add, buyer_profile.credits,
    paid_order.cashfree_order_id, concat('Cashfree ', paid_order.plan_id, ' purchase')
  );

  return true;
end;
$$;

revoke all on function public.fulfill_cashfree_order(text, text) from public;
grant execute on function public.fulfill_cashfree_order(text, text) to service_role;

