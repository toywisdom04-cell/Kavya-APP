security definer set search_path = public
as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;

  delete from public.payment_orders where user_id = uid;
  delete from public.user_media_unlocks where user_id = uid;
  delete from public.credit_transactions where user_id = uid;
  delete from public.buyer_records where user_id = uid;
  delete from auth.users where id = uid;
end;
$$;

