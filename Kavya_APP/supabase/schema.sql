create or replace function public.unlock_media_for_current_user(p_media_id uuid)
returns json
language plpgsql
security definer set search_path = public
as $$
declare
  media_item public.media;
  current_user_id uuid := auth.uid();
  current_user_credits integer;
  new_credit_balance integer;
begin
  -- Step 1: Verify the media item exists and get its cost.
  select * into media_item from public.media where id = p_media_id;
  if not found then
    raise exception 'MEDIA_NOT_FOUND';
  end if;

  -- Step 2: Check if user has already unlocked this item.
  if exists (select 1 from public.user_media_unlocks where user_id = current_user_id and media_id = p_media_id) then
    return json_build_object('status', 'already_unlocked', 'media_id', p_media_id, 'credits_balance', (select credits from public.profiles where id = current_user_id));
  end if;

  -- Step 3: Get current user's credits and check if they have enough.
  select credits into current_user_credits from public.profiles where id = current_user_id;
  if current_user_credits < media_item.credit_cost then
    raise exception 'INSUFFICIENT_CREDITS';
  end if;

  -- Step 4: Atomically deduct credits.
  update public.profiles
  set credits = credits - media_item.credit_cost
  where id = current_user_id
  returning credits into new_credit_balance;

  -- Step 5: Record the unlock and its credit usage in the same transaction.
  insert into public.user_media_unlocks (user_id, media_id)
  values (current_user_id, p_media_id);
  insert into public.credit_transactions (
    user_id, transaction_type, amount, balance_after, reference_id, description
  )
  values (
    current_user_id, 'media_unlock', -media_item.credit_cost, new_credit_balance,
    p_media_id::text, concat('Unlocked ', media_item.title)
  );

  -- Step 6: Return success with the new balance.
  return json_build_object('status', 'unlocked', 'media_id', p_media_id, 'credits_balance', new_credit_balance);
exception
  when others then
    return json_build_object('status', 'error', 'message', SQLERRM);
end;
$$;

revoke all on function public.unlock_media_for_current_user(uuid) from public;
grant execute on function public.unlock_media_for_current_user(uuid) to authenticated;

create or replace function public.deduct_chat_credit()
returns boolean
language plpgsql
security definer set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  current_user_credits integer;
  new_credit_balance integer;
begin
  select credits into current_user_credits from public.profiles where id = current_user_id;
  if current_user_credits is null or current_user_credits < 1 then
    return false;
  end if;

  update public.profiles
  set credits = credits - 1
  where id = current_user_id
  returning credits into new_credit_balance;

  insert into public.credit_transactions (
    user_id, transaction_type, amount, balance_after, description
  )
  values (
    current_user_id, 'chat', -1, new_credit_balance, 'Chat message credit'
  );

  return true;
end;
$$;

